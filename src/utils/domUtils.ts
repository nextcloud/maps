/**
 * @param unsafe raw text to embed as HTML, in element content or a quoted attribute value
 */
export function escapeHtml(unsafe: string): string {
	return String(unsafe ?? '')
		.replace(/&/g, '&amp;')
		.replace(/</g, '&lt;')
		.replace(/>/g, '&gt;')
		.replace(/"/g, '&quot;')
		.replace(/'/g, '&#39;')
}
